#!/usr/bin/env bash
# Everything that must pass before a change is done. Run from anywhere:   bash check.sh
#
#   1. pipeline: Python tests (Light List and notices reading, symbols, words, matching, zooms, tiles, the job
#      on a small real fixture, refusals, publish order)
#   2. fixtures: regenerate the parity fixtures (flutter/vm_aton/test/fixtures/, worker/test/fixtures/) from the
#      Python reference
#   3. worker: node tests (routes, keys, tiles out of the archive, cache)
#   4. preview: aton.js against the fixtures + a browser test on a fresh SAMPLE build (needs Chrome; else skipped)
#   5. flutter/vm_aton: flutter analyze + flutter test, incl. the Dart/Python parity test
#      (skipped with a note if Flutter isn't installed, or with SKIP_FLUTTER=1)
# Generated files that were out of date are rewritten (commit them); in CI (CI=true) that is a failure.
# Python: uses .venv (made by local.sh) if it's there, else python3 (needs pipeline/requirements-test.txt).
# Exit code 0 = all passed.
set -uo pipefail
root="$(cd "$(dirname "$0")" && pwd)"
cd "$root"
fail=0
step() { printf '\n== %s\n' "$1"; }
bad() { echo "FAILED: $1"; fail=1; }
stale() {
  if [ "${CI:-}" = "true" ]; then bad "$1 was out of date: run bash check.sh locally and commit the result"
  else echo "NOTE: $1 was out of date and has been rewritten. Review the diff and commit it with your change."; fi
}
run_node() {  # folder, what to say on failure
  local out rc
  out="$(cd "$1" && node --test --test-reporter=tap test/*.test.mjs 2>&1)"; rc=$?
  echo "$out" | grep -E "^# (tests|pass|fail|skipped) "
  if [ "$rc" != 0 ]; then echo "$out" | grep -A30 "^not ok" | head -150; bad "$2"; fi
}
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
py=python3
[ -x "$root/.venv/bin/python3" ] && py="$root/.venv/bin/python3"
if ! "$py" -c "import PIL, mapbox_vector_tile, pmtiles, requests, pytest" 2>/dev/null; then
  echo "Python packages missing. Once:  python3 -m venv .venv && .venv/bin/pip install -r pipeline/requirements-test.txt"
  exit 1
fi

step "1/5 pipeline tests"
(cd pipeline && "$py" -m pytest -q -p no:cacheprovider -W ignore::DeprecationWarning) || bad "pipeline tests"

step "2/5 parity fixtures for the app's, the preview's and the Worker's tests"
for fx in flutter/vm_aton/test/fixtures worker/test/fixtures; do
  mkdir -p "$tmp/before/$fx"; cp -R "$fx/." "$tmp/before/$fx/" 2>/dev/null || true
done
if "$py" pipeline/tools/make_parity.py; then
  for fx in flutter/vm_aton/test/fixtures worker/test/fixtures; do
    diff -rq "$tmp/before/$fx" "$fx" >/dev/null || stale "$fx (generated by pipeline/tools/make_parity.py)"
  done
else
  bad "pipeline/tools/make_parity.py"
fi

step "3/5 worker tests"
[ -d worker/node_modules ] || (cd worker && npm install --silent)
run_node worker "worker tests"

step "4/5 preview tests"
[ -d preview/node_modules ] || (cd preview && npm install --silent)
echo "building a SAMPLE site for the browser test (a few seconds)..."
if "$py" pipeline/run_aton.py --sample --out "$tmp/site" > "$tmp/sample.log" 2>&1; then
  export SITE_DIR="$tmp/site"
else
  cat "$tmp/sample.log"; bad "sample build for the preview test"
fi
run_node preview "preview tests"

step "5/5 flutter/vm_aton"
if [ "${SKIP_FLUTTER:-}" = 1 ]; then
  echo "skipped (SKIP_FLUTTER=1)"
elif command -v flutter >/dev/null; then
  (cd flutter/vm_aton && flutter pub get >/dev/null && flutter analyze && flutter test) \
    || bad "flutter analyze / flutter test (words_test.dart failing = words.dart no longer matches pipeline/vmaton/words.py)"
else
  echo "skipped: Flutter isn't installed here (CI and the mobile team run it)"
fi

echo
if [ "$fail" = 0 ]; then echo "ALL CHECKS PASSED"; else echo "SOME CHECKS FAILED"; fi
exit "$fail"
